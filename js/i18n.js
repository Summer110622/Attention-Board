const DICTS = { en: EN, ja: JA };
let lang = 'en';

export function detectLang() {
  try {
    const saved = localStorage.getItem('ab-lang');
    if (saved === 'en' || saved === 'ja') return saved;
  } catch (e) { /* ignore */ }
  return (typeof navigator !== 'undefined' && /^ja/i.test(navigator.language || '')) ? 'ja' : 'en';
}
export function setLang(l) {
  lang = l === 'ja' ? 'ja' : 'en';
  try { localStorage.setItem('ab-lang', lang); } catch (e) { /* ignore */ }
  if (typeof document !== 'undefined') document.documentElement.lang = lang;
}
export const getLang = () => lang;

export function t(key, args) {
  let s = (DICTS[lang] && DICTS[lang][key]) || EN[key] || key;
  if (args) s = s.replace(/\{(\w+)\}/g, (m, k) => (args[k] !== undefined ? args[k] : m));
  return s;
}
